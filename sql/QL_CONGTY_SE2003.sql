USE QL_CONGTY_SE2003
--BƯỚC 3: TẠO TABLE TRONG DATABASE QL_CONGTY_SE2003
CREATE TABLE NHANVIEN
(
	MANV DECIMAL(18,0) NOT NULL PRIMARY KEY,
	TENNV NVARCHAR(200),
	DIACHI NVARCHAR(200),
	LUONG MONEY,
	GIOITINH CHAR (5),
	NGAYSINH DATE,
	MAPHG INT,
	MANGS DECIMAL(18,0),
	NGAYNC DATE -- NGÀY CUỐI CÙNG K CÓ DẤU PHẨY
)
-- PHONG BAN
CREATE TABLE PHONGBAN
(
	MAPHG INT NOT NULL PRIMARY KEY,
	TENPHG NVARCHAR (200),
	MATRUONGPHG DECIMAL (18,0),
	NGAYBD DATE,
--TẠO RÀNG BUỘC KHÓA NGOẠI
-- RÀNG BUỘC TÊN RB KHÓA NGOẠI (CỘT) CHIẾU TỚI BẢNG CHA (CỘT)
	CONSTRAINT FK_MATRUONGPHG FOREIGN KEY(MATRUONGPHG) REFERENCES NHANVIEN(MANV)
)
--ĐỊA ĐIỂM
CREATE TABLE DIADIEM
(
	MADD INT NOT NULL PRIMARY KEY,
	TENDD NVARCHAR (200)
)
-- DỰ ÁN 
CREATE TABLE DUAN
(
	MADA INT NOT NULL PRIMARY KEY,
	TENDA NVARCHAR (200),
	MADD INT ,
	MAPHG INT,
	CONSTRAINT FK_MADD FOREIGN KEY (MADD) REFERENCES DIADIEM(MADD),
	CONSTRAINT FK_MAPHG FOREIGN KEY (MAPHG) REFERENCES PHONGBAN(MAPHG)
)
-- PHÂN CÔNG
CREATE TABLE PHANCONG
(
	MANV DECIMAL (18,0) NOT NULL ,
	MADA INT NOT NULL ,
	SOGIO INT,
-- TRƯỜNG HỢP 1 TABLE CÓ TỪ 2 ATTRIBETE LÀ KHÓA CHÍNH PHẢI VIẾT NHƯ SAU
	CONSTRAINT PK_MANV_MADA PRIMARY KEY (MANV,MADA),
	CONSTRAINT FK_MAVN FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
	CONSTRAINT FK_MADA FOREIGN KEY (MADA) REFERENCES DUAN(MADA)
)
-- NGƯỜI PHỤ THUỘC
CREATE TABLE NGUOIPHUTHUOC
(
	TENNPT NVARCHAR (200) NOT NULL,
	MANV DECIMAL (18,0) NOT NULL,
	GIOITINH CHAR(5),
	NGAYSINH DATE,
	TENMQH NVARCHAR (200),
	CONSTRAINT PK_TENNPT_MANV PRIMARY KEY (TENNPT,MANV),
	CONSTRAINT FK_MANV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)
)
--PHÂN CÔNG ĐỊA ĐIỂM
CREATE TABLE PHANCONGDD
(
	 MAPHG INT NOT NULL,
	 MADD INT NOT NULL,
	 CONSTRAINT PK_MAPHG_MADD PRIMARY KEY (MAPHG,MADD),
	 CONSTRAINT FK_MAPHG2 FOREIGN KEY (MAPHG) REFERENCES PHONGBAN(MAPHG),
	 CONSTRAINT FK_MADD2 FOREIGN KEY (MADD) REFERENCES DIADIEM(MADD)
)
