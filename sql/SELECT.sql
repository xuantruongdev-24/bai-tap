--HÀM THỐNG KÊ : MIN, MAX, COUNT,SUM,AVG
-- MỆNH ĐỀ GOM NHÓM : GROUP BY
-- VIDU 16:  TÍNH LƯƠNG TRUNG BÌNH CỦA TẤT CẢ NHÂN VIÊN 
SELECT AVG(NV.LUONG) N'LƯƠNG TRUNG BÌNH'
FROM NHANVIEN NV
--VIDU 17: LẤY RA TT GỒM MAPB, TENPB, LƯƠNG TB Ở TỪNG PHÒNG BAN
SELECT PB.MAPHG, PB.TENPHG, AVG(NV.LUONG) N'LƯƠNG TRUNG BÌNH'
FROM NHANVIEN NV, PHONGBAN PB
WHERE NV.MAPHG = PB.MAPHG
GROUP BY PB.MAPHG,PB.TENPHG
-- KHI SỬ DỤNG MỆNH ĐỀ GROUP BY BẮT BUỘC PHẢI GROUP BY HẾT NHỮNG ATTRIBUTE TRONG MỆNH ĐỀ SELECT
--NGOẠI TRỪ DERIVED ATTIBUT

--VIDU 18: LẤY RA THÔN TIN MADD, TENDD, TỔNG SỐ DỰ ÁN TRIỂN KHAI TẠI ĐỊA ĐIỂM ĐÓ

SELECT DD.MADD, DD.TENDD, COUNT(DA.MADA) 
FROM DUAN DA, DIADIEM DD 
WHERE DA.MADD = DD.MADD
GROUP BY  DD.MADD, DD.TENDD
--VIDU 19: LẤY RA TT GỒM MAPHG, TENPHG, TỔNG SỐ NHÂN VIÊN ĐANG LÀM VIỆC TẠI PHÒNG BAN ĐÓ

SELECT PB.MAPHG,PB.TENPHG, COUNT(NV.MAPHG)N'TONG NHAN VIEN'
FROM PHONGBAN PB, NHANVIEN NV
WHERE NV.MAPHG = PB.MAPHG
GROUP BY PB.MAPHG,PB.TENPHG

--VIDU 20: LẤY RA THÔNG TIN GỒM MANV, TENNV, TỔNG SỐ GIỜ MÀ NHÂN VIÊN ĐÓ ĐÃ THAM GIA TẤT CẢ DỰ ÁN

SELECT PC.MANV,PC.MADA, SUM(SOGIO)N'TỔNG SỐ GIỜ'
FROM NHANVIEN NV, PHANCONG PC
WHERE PC.MANV= NV.MANV
GROUP BY PC.MANV,PC.MADA


