SELECT * FROM NHANVIEN

-- VÍ DỤ 2: LẤY RA THÔNG TIN GỒM MANV, TENNV, LUONG, GIOITINH CỦA NHỮNG NV CÓ GIỚI TÍNH LÀ F
 SELECT MANV, TENNV, LUONG, GIOITINH FROM NHANVIEN WHERE GIOITINH = 'F'

/*
	KHI SO SÁNH VỚI CHUỖI TẠI MỆNH ĐỀ WHERE
	- SỬ DỤNG SO SÁNH = TRONG TRƯƠNG HỢP SO SÁNH CHÍNH XÁC VỚI CHUỖI
	- SỬ DỤNG SO SÁNH LIKE TRONG TRƯỜNG HỢP SO SÁNH 1 ĐOẠN TRONG CHUỖI
*/

-- VÍ DỤ 3: LẤY RA MANV, TENNV, DIACHI CỦA NHỮNG NHÂN VIÊN CÓ TÊN CHỨA CHỮ THỊ

SELECT MANV, TENNV, DIACHI FROM NHANVIEN WHERE TENNV LIKE N'%THỊ%'

-- VÍ DỤ 4: LẤY RA THÔNG TIN NHỮNG NHÂN VIÊN CÓ TÊN KẾT THÚC CUỐI CÙNG ALF KÝ TỰ G

SELECT * FROM NHANVIEN WHERE TENNV LIKE N'%G'

-- USING ALIAS NAME IN SELECT CLAUSE: SỬ DỤNG ĐẶT TÊN BÍ DANH TRONG MỆNH ĐỀ SELECT

-- VÍ DỤ 4: LẤY THÔNG TIN GỒM MANV 'MÃ NHÂN VIÊN', TENNV'TÊN NHÂN VIÊN'
-- GIOITINH 'PHÁI'
-- CỦA NHỮNG NHÂN VIÊN CÓ ĐỊA CHỈ TẠI HÀ NỘI

SELECT MANV AS N'MÃ NHÂN VIÊN', TENNV AS N'TÊN NHÂN VIÊN', GIOITINH AS N'PHÁI' FROM NHANVIEN
WHERE DIACHI LIKE N'%HÀ NỘI%'

-- KHI SỬ DỤNG ALIAS NAME CÓ THỂ DÙNG TỪ KHÓA AS HOẶC KHÔNG ĐỀU ĐƯỢC

-- KẾT HỢP NHIỀU ĐIỀU KIỆN TRONG MỆNH ĐỀ WHERE
-- VÍ DỤ 5: LẤY RA THÔNG TIN GỒM MANV, TENNV, TUOI, GIOITINH
-- CỦA NHỮNG NHÂN VIÊN CÓ TUỔI LỚN HƠN 50 VÀ GIỚI TÍNH LÀ F
-- HOẶC TUỔI > 40 VÀ GIỚI TÍNH LÀ M

SELECT MANV, TENNV, YEAR(GETDATE()) - YEAR(NGAYSINH) AS TUOI, GIOITINH FROM NHANVIEN
WHERE ( YEAR(GETDATE()) - YEAR(NGAYSINH) > 50 AND GIOITINH = 'F') OR ( YEAR(GETDATE()) - YEAR(NGAYSINH) > 40 AND GIOITINH = 'M')

-- Mệnh đề ORDER BY : SẮP XẾP, ASC (TĂNG)/ DESC (GIẢM)
-- VÍ DỤ 6: LẤY RA THÔNG TIN GỒM MANV, TENNV, MAPHG, LUONG
-- CỦA NHỮNG NHÂN VIÊN CÓ GIỚI TÍNH LÀ F
-- SẮP XẾP MAPHG TĂNG, LƯƠNG GIẢM

SELECT MANV, TENNV, MAPHG, LUONG FROM NHANVIEN
WHERE GIOITINH = 'F'
ORDER BY MAPHG ASC, LUONG DESC


-- QUERY ONE MORE THAN RELATION: VIẾT CÂU TRUY VẤN TRÊN NHIỀU HƠN 1 QUAN HỆ
-- BẮT BUỘC PHẢI SỬ DỤNG PHÉP KẾT KHI VIẾT CÂU TRUY VẤN TRÊN NHIỀU HƠN 1 QUAN HỆ
-- NẾU THIẾU ĐÁP ÁN SẼ HOÀN TOÀN SAI
-- VÍ DỤ 7: LẤY RA THÔNG TIN GỒM MANV, TENNV, TENPB MÀ NHÂN VIÊN ĐÓ ĐANG LÀM VIỆC

SELECT NV.MANV, NV.DIACHI, PB.TENPHG FROM NHANVIEN NV, PHONGBAN PB
WHERE NV.MAPHG = PB.MAPHG -- ĐIỀU KIỆN KẾT BẮT BUỘC KHÔNG ĐƯỢC THIẾU

-- VÍ DỤ 8: LẤY RA THÔNG TIN GỒM MADA, TENDA, TENDD TRIỂN KHAI NHỮNG DỰ ÁN CÓ TÊN TẠI HÀ NỘI
SELECT DA.MADA, DA.TENDA, DD.TENDD FROM DUAN DA, DIADIEM DD
WHERE DD.TENDD LIKE N'%HÀ NỘI%'AND DA.MADD = DD.MADD

-- DISTINCT: LOẠI BỎ NHỮNG DÒNG TRÙNG NHAU
-- VÍ DỤ 9: HÃY CHO BIẾT NHỮNG ĐỊA CHỈ THƯỜNG TRÚ MÀ NHÂN VIÊN ĐANG Ở
SELECT DISTINCT NV.DIACHI
FROM NHANVIEN NV

-- DÙNG CÁCH VIẾT SỬ DỤNG TẬP SET OPERATORS: UNION, INTERSECT, EXCEPT
-- VÍ DỤ 10:LẤY RA THÔNG TIN NHỮNG NHÂN VIÊN CÓ LƯƠNG > 80000 HOẶC GIỚI TÍNH LÀ F
SELECT NV.* FROM NHANVIEN NV
WHERE NV.LUONG > 80000 OR NV.GIOITINH = 'F'

-- CÁCH 2:
SELECT NV.* FROM NHANVIEN NV WHERE NV.LUONG > 80000
UNION
SELECT NV.* FROM NHANVIEN NV WHERE NV.GIOITINH = 'F'

-- VÍ DỤ 11: LẤY RA THÔNG TIN GỒM MANV, TENNV CỦA NHỮNG NHÂN VIÊN KHÔNG PHẢI LÀ NGƯỜI GIÁM SÁT
SELECT NV.MANV, NV.TENNV FROM NHANVIEN NV
WHERE NV.MANV IN (SELECT NV.MANV FROM NHANVIEN NV
				  EXCEPT
				  SELECT DISTINCT NV.MANGS FROM NHANVIEN NV)

/*
	SUB QUERIES IN WHERE CLAUSE:
	LÀ VIẾT TRUY VẤN LỒNG TRONG MỆNH ĐỀ WHERE 
	- NẾU TRUY VẤN CON TRẢ RA 1 LIST CÁC VALUE(NHỀU HƠN 1 VALUE) THÌ TẠI MỆNH ĐỀ WHERE SỬ DỤNG ĐIỀU KIỆN SO SÁNH LÀ IN, NOT IN, EXIST, NOT EXIST,...
	- NẾU TRUY VẤN CON TRẢ RA 1 VALUE DUY NHẤT THÌ TẠI MỆNH ĐỀ WHERE SỬ DỤNG  ĐIỀU KIỆN SO SÁNH LÀ >, <, >=, <=, ==, =, !=,...
*/

-- VÍ DỤ 12: LẤY RA THÔNG TIN GỒM MANV, TENNV CỦA NHỮNG NGƯỜI NHÂN VIÊN ĐANG LÀM VIỆC TẠI PHÒNG CÓ TÊN LÀ PHÒNG PHẦN MỀM TRONG NƯỚC

SELECT NV.MANV, NV.TENNV FROM NHANVIEN NV
WHERE NV.MAPHG = ( SELECT PB.MAPHG FROM PHONGBAN PB WHERE PB.TENPHG = N'PHÒNG PHẦN MỀM TRONG NƯỚC')

-- SUB IN FROM CLAUSE : VIẾT TRUY VẤN LỒNG TẠI MỆNH ĐỀ FROM
-- ĐÂY LÀ CÁCH VIẾT TẠO RA 1 BẢNG ẢO TẠO FROM XỬ LÝ THEO YÊU CẦU ĐỀ BÀI 
--VIDU13: LẤY RA THÔNG TIN GỒM MANV, TENNV, MANGS CỦA NHỮNG NGƯỜI GIẢM SÁT CÓ TÊN LÀ MAI DUY AN
SELECT NV.MANV, NV.TENNV, NV.MANGS
FROM (
    SELECT MANV AS MANGS
    FROM NHANVIEN 
    WHERE TENNV = N'MAI DUY AN'
) A, NHANVIEN NV
WHERE A.MANGS = NV.MANGS;
--VIDU14: LẤY RA THÔNG TIN GỒM MANV, TENNV, MANGS, TENNGS CỦA NHUNG NGƯỜI GIÁM SÁT CÓ ĐỘ TUỔI > 55

SELECT  NV.MANV 'MANGS', NV.TENNV 'TENNGS' ,YEAR(GETDATE())- YEAR(NV.NGAYSINH) N'TUỔI'
FROM 
	(SELECT DISTINCT NV.MANGS
		FROM NHANVIEN NV)A, NHANVIEN NV
WHERE A.MANGS = NV.MANV
AND YEAR(GETDATE())- YEAR(NV.NGAYSINH) > 55 ) XYZ, NHANVIEN NV

WHERE XYZ = NV.MANGS
