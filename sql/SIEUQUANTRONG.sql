--VIDU5: VIẾT FUNCTION VỚI THAM SỐ VÀO LÀ TENNV
--LẤY RA THÔNG TIN MANV, TUỔI CỦA NHÂN VIÊN ĐÓ VÀ TỔNG SỐ 
--DỰ ÁN MÀ NV ĐÓ ĐÃ THAM GI
-- MANV | TUOI |TONGDA
GO
CREATE FUNCTION FNC_VD05 (@TENNV NVARCHAR(200))
RETURNS @THONGKE TABLE
(
	MANV DECIMAL(18,0),
	TUOI INT,
	TONGDA INT
)
AS
	BEGIN
	--MANV| TUOI | TONGDA
	INSERT INTO @THONGKE
	SELECT NV.MANV, YEAR(GETDATE()) -YEAR(NV.NGAYSINH),COUNT (PC.MADA)
	FROM NHANVIEN NV, PHANCONG PC
	WHERE NV.MANV = PC.MANV
	AND NV.TENNV = @TENNV
	GROUP BY NV.MANV, YEAR(GETDATE())- YEAR(NV.NGAYSINH)
	RETURN-- BẮT BUỘC PHẢI CÓ THEO FORMAT FUNVTION, MẶC ĐỊNH RETURN @THONGKE
	END
-- THỰC THI
