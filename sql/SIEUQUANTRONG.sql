CREATE FUNCTION FNC_VD2(@TENNGS NVARCHAR(200))
RETURNS INT
AS	
	BEGIN
	DECLARE @TONGNV INT
	SET @TONGNV = (SELECT COUNT (NV.MANV)
					FROM(SELECT NV.MANV 'MANGS'
							FROM NHANVIEN NV
							WHERE NV.TENNV = @TENNGS)A,NHANVIEN NV
					WHERE A.MANGS = NV.MANGS)
	RETURN @TONGNV

END
--THỰC THI
GO
