CREATE TRIGGER TRIG_VD02
ON NHANVIEN
FOR INSERT, UPDATE
AS
	BEGIN
		DECLARE @KTGIOITINH CHAR(5)
		SET @KTGIOITINH = (SELECT INS.GIOITINH
							FROM NHANVIEN NV , inserted INS
							WHERE NV.MANV = INS.MANV
							)
		IF(@KTGIOITINH NOT IN ('F', 'M'))
		BEGIN
			PRINT N'GIỚI TÍNH NHẬP VÀO PHẢI LÀ F HOẶC M!!!!!!'
			ROLLBACK
			END
		END
