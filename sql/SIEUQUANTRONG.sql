CREATE FUNCTION FNC_VD01 (@TENNV NVARCHAR(200))
RETURNS INT--DẠNG 1 FUNCTION KDL, RETURNS 'CÓ S'
AS
	BEGIN
		DECLARE @TONG INT
		SET @TONG = ( SELECT SUM(PC.SOGIO)	
						FROM NHANVIEN NV , PHANCONG PC
						WHERE NV.MANV =PC.MANV
						AND NV.TENNV =@TENNV)
		RETURN @TONG
	END
GO
-- thực thi
