CREATE TRIGGER TRG_VD01
ON NHANVIEN--TRIGGER VIẾT TABLE NÀO ?
FOR INSERT-- TRIGGER VIẾT CHO SỰ KIỆN NÀO?
AS
	BEGIN
		DECLARE @KTTUOI INT
		SET @KTTUOI =(SELECT YEAR(GETDATE()) - YEAR(INS.NGAYSINH)
						FROM inserted INS)
