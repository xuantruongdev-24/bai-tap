CREATE FUNCTION FNC_VD04 (@TENDD NVARCHAR(200))
RETURNS TABLE
	RETURN (SELECT DA.*
			FROM DUAN DA, DIADIEM DD
			WHERE DA.MADD = DD.MADD
			AND DD.TENDD =@TENDD
				)
--THỰC THI
