CREATE FUNCTION FNC_VD03 (@TENPB NVARCHAR(200))
RETURNS TABLE
AS
	RETURN (SELECT NV.*
				FROM NHANVIEN NV, PHONGBAN PB
				WHERE NV.MAPHG = PB.MAPHG
				AND PB.TENPHG = @TENPB)
-- THỰC THI
